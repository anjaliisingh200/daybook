import { chromium } from "playwright-core";
const b = await chromium.launch({ channel: "msedge", headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://localhost:3000/tasks?s=" + Date.now(), { waitUntil: "load", timeout: 120000 });
await p.waitForTimeout(6000);
await p.locator("article[data-task]").first().click();
await p.waitForTimeout(800);
const sheet = p.locator('aside[role=dialog][aria-label="Task details"]');
await sheet.getByPlaceholder("Subtask title").count();
await sheet.getByRole("button", { name: "Add subtask" }).click();
await sheet.getByPlaceholder("Subtask title").fill("Book the venue");
await sheet.getByPlaceholder("Subtask title").press("Enter");
await p.waitForTimeout(700);
await sheet.getByPlaceholder("Subtask title").fill("Send invites");
await sheet.getByPlaceholder("Subtask title").press("Enter");
await p.waitForTimeout(700);
await p.waitForTimeout(300);
await p.screenshot({ path: "docs/changelog/screenshots/2026-11-19-subtask-rows/task-sheet-subtasks.png" });
console.log(JSON.stringify({ rows: await sheet.locator("div.h-9").count() }));
await b.close();
